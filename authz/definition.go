// Package member is the authorization member (boundary card infra/authz): it takes the definitions every component
// submits, keeps the security records (management units and holdings, role revisions, grants) changed only through
// the effect point, and answers view verifications from the committed records (security 03, 08, 09a). Step 5 of the
// representative deployment experiment: confirmations, the strict path, member switching, sharing, delegation and
// appointment-bound grants are not here; what needs them answers CAPABILITY_UNSUPPORTED.
package authz

import (
	"embed"
	"io/fs"

	sdkauthz "github.com/brickKit/be-sdk-go/v3/authz"
	"github.com/brickKit/be-sdk-go/v3/component"
	"github.com/brickKit/be-sdk-go/v3/config"
	"github.com/brickKit/be-sdk-go/v3/runtime"
)

// Identity of the component.
const (
	ID      = "infra/authz"
	Version = "3.0.10"
)

// The member's own resource and operations: the security records on the user surface, the two system methods.
const (
	Records        = "infra.authz.security_record"
	OpRead         = "infra.authz.security_record.read"
	OpChange       = "infra.authz.security_record.change"
	System         = "infra.authz.system"
	OpVerify       = "infra.authz.system.verify"
	OpSubmit       = "infra.authz.system.submit"
	SystemRead     = "infra.authz.system.read"
	GRPCPort       = 9223
	ShardDomain    = "authz.view."
	SecurityDomain = "authz.security.deployment"
)

//go:embed migrations/*.sql
var migrationFiles embed.FS

func migrations() fs.FS {
	sub, _ := fs.Sub(migrationFiles, "migrations")
	return sub
}

// Keys are the component's own configuration keys.
func Keys() []config.Key {
	return []config.Key{
		// this member's instance identity: generated at installation, kept with the deployment's run files, never the
		// same in two deployments (protocol 14 rule 3); views carry it
		{Name: "AUTHZ_INSTANCE", Type: config.String, Required: true},
		// the registry's owners of resource types and permission keys (TSV: kind, key, owner_component), generated by
		// the assembly; usually file:// or AUTHZ_REGISTRY_FILE. Not secret: a secret key so that file:// delivers the content
		{Name: "AUTHZ_REGISTRY", Type: config.String, Required: true, Secret: true},
		// the install claim, simplified: this principal becomes the first authorization admin of an empty member
		{Name: "AUTHZ_BOOTSTRAP_ADMIN", Type: config.String},
	}
}

// Definitions are the member's own declarations: it guards its user surface with a view like any component.
func Definitions() *sdkauthz.Definitions {
	none := map[string]sdkauthz.Dimension{}
	return &sdkauthz.Definitions{Component: ID,
		Resources: []sdkauthz.Resource{
			{Type: Records, ViewOperation: OpRead, Dimensions: none, Fields: map[string]sdkauthz.Field{
				"id": {Class: sdkauthz.Ordinary}, "record_type": {Class: sdkauthz.Ordinary}, "state": {Class: sdkauthz.Ordinary},
				"body": {Class: sdkauthz.Ordinary}}},
			{Type: System, ViewOperation: SystemRead, Dimensions: none, Fields: map[string]sdkauthz.Field{}}},
		Operations: []sdkauthz.Operation{
			{Key: OpRead, ResourceType: Records, Purpose: "read", RiskClass: "low"},
			{Key: OpChange, ResourceType: Records, Purpose: "manage", RiskClass: "high", SideEffects: []string{"security_change"},
				Audit: true},
			{Key: SystemRead, ResourceType: System, Purpose: "read", RiskClass: "low"},
			{Key: OpVerify, ResourceType: System, Purpose: "read", RiskClass: "low"},
			{Key: OpSubmit, ResourceType: System, Purpose: "manage", RiskClass: "low", SideEffects: []string{"security_change"}},
		}}
}

// Definition is the component as the launcher and the shells take it.
func Definition() component.Definition {
	return component.Definition{ID: ID, Version: Version, Keys: Keys(), Migrations: migrations(), GRPCPort: GRPCPort,
		Authz: Definitions(), New: func(rt *runtime.Runtime) (component.Module, error) { return New(rt) }}
}
