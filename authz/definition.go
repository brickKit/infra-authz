// Package member is the authorization member (boundary card infra/authz): it takes the definitions every component
// submits, keeps the security records (management units and holdings, role revisions, grants) changed only through
// the effect point, and answers view verifications from the committed records (security 03, 08, 09a). Step 5 of the
// representative deployment experiment: confirmations, the strict path, member switching, sharing, delegation and
// appointment-bound grants are not here; what needs them answers CAPABILITY_UNSUPPORTED.
package authz

import (
	"embed"
	"io/fs"

	claim "github.com/brickKit/infra-authz/v3/internal/claim"
	core "github.com/brickKit/infra-authz/v3/internal/core"
	effectpoint "github.com/brickKit/infra-authz/v3/internal/effectpoint"
	plans "github.com/brickKit/infra-authz/v3/internal/plans"

	"github.com/brickKit/be-sdk-go/v3/component"
	"github.com/brickKit/be-sdk-go/v3/config"
	"github.com/brickKit/be-sdk-go/v3/runtime"
)

//go:embed migrations/*.sql
var migrationFiles embed.FS

func migrations() fs.FS {
	sub, _ := fs.Sub(migrationFiles, "migrations")
	return sub
}

// Keys are the component's own configuration keys.
func Keys() []config.Key {
	return []config.Key{
		// this member's instance identity: generated at installation, kept with the deployment's run files, never the
		// same in two deployments (protocol 14 rule 3); views carry it
		{Name: "AUTHZ_INSTANCE", Type: config.String, Required: true},
		// the registry's owners of resource types and permission keys (TSV: kind, key, owner_component, a permission key's
		// retirement), generated by
		// the assembly; usually file:// or AUTHZ_REGISTRY_FILE. Not secret: a secret key so that file:// delivers the content
		{Name: "AUTHZ_REGISTRY", Type: config.String, Required: true, Secret: true},
		// the install claim (A130): principal:<platform principal> or code:sha256:<hex of a one-time code>; recorded at
		// installation, consumed once by its claimant (POST /api/authz/claim). Secret: a code's digest is the claim
		{Name: "AUTHZ_INSTALL_CLAIM", Type: config.String, Secret: true},
		{Name: "AUTHZ_INSTALL_CLAIM_VALIDITY", Type: config.Duration, Default: claim.DefaultClaimValidity},
		// the deployment owner's confirmation key (A124): an Ed25519 public key (PEM); its private key is kept offline
		// by the owner and signs owner confirmations. Absent: no owner confirmation is accepted. Not secret: a secret
		// key so that file:// delivers it
		{Name: "AUTHZ_OWNER_KEY", Type: config.String, Secret: true},
		// the deployment owner's recovery key (security 08's administrator recovery, A129): an Ed25519 public key (PEM),
		// another key than AUTHZ_OWNER_KEY; its private key is kept offline and signs recovery requests (cmd/recover).
		// Absent: no recovery is accepted. Not secret: a secret key so that file:// delivers it
		{Name: "AUTHZ_RECOVERY_KEY", Type: config.String, Secret: true},
		// the identity member: its system surface ($endpoint:<member>:grpc) and its component ID (the certificate it
		// presents, the source's name); config/vars.yaml gives both, changed together when the member is switched
		{Name: "IAM_GRPC_URL", Type: config.String, Required: true},
		{Name: "IAM_COMPONENT", Type: config.String, Required: true},
		// the employee member (mdm/employee), optional: its system surface and its component ID, given together; empty
		// when the deployment has none (every account is then a person by itself, no record binds an appointment)
		{Name: "EMPLOYEE_GRPC_URL", Type: config.String},
		{Name: "EMPLOYEE_COMPONENT", Type: config.String},
		// the attachment member (infra/attachment), optional: its component ID, the only caller of the attachment
		// category catalog; empty when the deployment has none
		{Name: "ATTACHMENT_COMPONENT", Type: config.String},
		// D_src_high and D_src_read (security 03): the watermark ages at which high-risk operations, then ordinary
		// reads, close for views that depend on the identity source
		{Name: "AUTHZ_SOURCE_HIGH", Type: config.Duration, Default: core.DefaultSourceHigh},
		{Name: "AUTHZ_SOURCE_READ", Type: config.Duration, Default: core.DefaultSourceRead},
		// T_tight (security 03): how old the identity source's watermark may be for one person to tighten alone on the
		// last applied facts
		{Name: "AUTHZ_T_TIGHT", Type: config.Duration, Default: core.DefaultTight},
		// the levels of management units below the root (security 04: the depth of re-delegation is the profile's
		// explicit bound, A131): the root's max_subdelegation_depth when the install claim makes it, and no unit is made
		// deeper
		{Name: "AUTHZ_MAX_UNIT_DEPTH", Type: config.Integer, Default: int64(effectpoint.DefaultMaxUnitDepth)},
		// batch plans (security 08, A132): how long from the preview a plan may run; the items beyond which a plan is a
		// protected operation a second person confirms
		{Name: "AUTHZ_PLAN_MAX_AGE", Type: config.Duration, Default: plans.DefaultPlanMaxAge},
		{Name: "AUTHZ_PLAN_CONFIRM_ABOVE", Type: config.Integer, Default: int64(plans.DefaultPlanConfirmAbove)},
	}
}

// Definition is the component as the launcher and the shells take it.
func Definition() component.Definition {
	return component.Definition{ID: core.ID, Version: core.Version, Keys: Keys(), Migrations: migrations(), GRPCPort: core.GRPCPort,
		Subscribes: true, Evidence: true, Authz: core.Definitions(), Replay: core.OpReplay, Recovery: core.OpRecover,
		New: func(rt *runtime.Runtime) (component.Module, error) { return New(rt) }}
}
