package authz

import (
	"os"
	"testing"

	"github.com/brickKit/be-sdk-go/v3/launcher"
)

// ownKeys are the descriptions of the member's own keys in component.yaml.
var ownKeys = map[string]string{
	"AUTHZ_INSTANCE":        "this member's instance identity: generated once at installation (a UUID), kept with the deployment's run files, never the same in two deployments; views carry it",
	"AUTHZ_OWNER_KEY":       "the deployment owner's confirmation key (A124): an Ed25519 public key in PEM; its private key is kept offline by the owner and signs owner confirmations; absent, no owner confirmation is accepted. Not sensitive: a secret key so that file:// delivers it (or AUTHZ_OWNER_KEY_FILE)",
	"AUTHZ_REGISTRY":        "the registry's owners of resource types and permission keys: TSV with kind (resource_type or permission), key, owner_component and, for a retired permission key, its retirement date; generated by the assembly. Not sensitive: a secret key so that file:// delivers its content (or AUTHZ_REGISTRY_FILE)",
	"AUTHZ_BOOTSTRAP_ADMIN": "the install claim: the platform principal (UUIDv7) that becomes the first authorization admin of a member without any management; ignored afterwards",
	"IAM_GRPC_URL":          "the identity member's system surface, $endpoint:<identity member>:grpc (config/vars.yaml): the account status is pulled and read there",
	"IAM_COMPONENT":         "the identity member's component ID, e.g. infra/iam-casdoor (config/vars.yaml): the certificate it presents and the name of the account status source",
	"AUTHZ_SOURCE_HIGH":     "D_src_high (security 03, D64): a duration; default 1m, at most 5m. Views that depend on the identity source stop renewing high-risk operations past this watermark age",
	"AUTHZ_T_TIGHT":         "T_tight (security 03): a duration; default 1h. A tightening whose requester is judged by the last applied facts of the identity source is done by one person while the source's watermark is no older; beyond it, or on a stalled source, a second authorization admin or the deployment owner confirms",
	"AUTHZ_SOURCE_READ":     "D_src_read (security 03, D64): a duration; default 10m, at most 1h, no shorter than AUTHZ_SOURCE_HIGH. Past this watermark age the views close for ordinary reads too",
}

// TestTheManifestDeclaresWhatTheSDKReads: component.yaml's configSchema is exactly the keys the SDK reads.
func TestTheManifestDeclaresWhatTheSDKReads(t *testing.T) {
	raw, err := os.ReadFile("../component.yaml")
	if err != nil {
		t.Fatal(err)
	}
	if p := launcher.ManifestProblems(raw, Definition(), ownKeys); len(p) > 0 {
		t.Errorf("component.yaml's configSchema differs from what the SDK reads:\n%v\nthe block:\n%s", p,
			launcher.ConfigSchemaYAML(Definition(), ownKeys))
	}
}
